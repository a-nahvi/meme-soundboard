"""Prepare the app's embedded PNG from the owner's Iconly Local previews."""

import sys
from pathlib import Path

from PIL import Image, ImageSequence


# A means an Iconly animation. S means a matching static Iconly symbol.
SELECTION = [
    ("LIBRARY", "A", 3571),
    ("AUDIO_DEVICES", "S", 59119),
    ("MIX", "A", 2056),
    ("KEYBOARD", "A", 1522),
    ("APPEARANCE", "A", 2780),
    ("DOWNLOAD", "A", 1986),
    ("DOCUMENT", "S", 394),
    ("STOP", "S", 72947),
    ("MIC", "A", 3570),
    ("MIC_OFF", "A", 3562),
    ("WAVEFORM", "A", 3625),
    ("HEADPHONES", "A", 3548),
    ("WARNING", "S", 390),
    ("SUCCESS", "S", 797),
    ("CLOSE", "S", 802),
    ("PLUS", "S", 10960),
    ("FOLDER", "A", 2121),
    ("SEARCH", "A", 1363),
    ("STAR", "A", 2999),
    ("STAR_FILLED", "S", 134),
    ("DELETE", "A", 2716),
    ("PLAY", "A", 3584),
    ("RENAME", "A", 2824),
    ("TRIM", "A", 3368),
    ("MUSIC", "A", 3608),
    ("REFRESH", "A", 3225),
    ("EXTERNAL_LINK", "A", 1990),
    ("CHECK", "S", 801),
    ("MINIMIZE", "S", 10957),
    ("MAXIMIZE", "S", 13622),
    ("RESTORE", "S", 25504),
]

SIDE = 40
PADDING = 1
STRIDE = SIDE + 2 * PADDING
COLUMNS = 32
FRAME_MS = 20


def build(library, output):
    previews = library / "assets" / "previews"
    tiles = []
    entries = []
    for name, kind, resource_id in SELECTION:
        animated = kind == "A"
        folder, extension = ("animations", "gif") if animated else ("icons", "png")
        start = len(tiles)
        with Image.open(previews / folder / f"{resource_id}.{extension}") as preview:
            for frame in ImageSequence.Iterator(preview):
                if animated and frame.info.get("duration") != FRAME_MS:
                    raise ValueError(f"Unexpected frame interval in {folder}/{resource_id}")
                # Keep the stop glyph the visual weight of the play triangle.
                side = 27 if name == "STOP" else SIDE
                mask = frame.convert("RGBA").getchannel("A").resize(
                    (side, side), Image.Resampling.LANCZOS
                )
                tiles.append(mask)
        count = len(tiles) - start
        entries.append(
            f"    pub const {name}: Self = Self::new({start}, {count});"
            f" // Iconly {folder}/{resource_id}"
        )

    rows = (len(tiles) + COLUMNS - 1) // COLUMNS
    alpha = Image.new("L", (COLUMNS * STRIDE, rows * STRIDE))
    for index, tile in enumerate(tiles):
        inset = PADDING + (SIDE - tile.width) // 2
        alpha.paste(tile, (index % COLUMNS * STRIDE + inset, index // COLUMNS * STRIDE + inset))

    output.mkdir(parents=True, exist_ok=True)
    Image.merge("LA", (Image.new("L", alpha.size, 255), alpha)).save(
        output / "atlas.png", optimize=True
    )
    constants = [f"const {name}: usize = {value};" for name, value in [
        ("TILE_SIDE", SIDE), ("TILE_PADDING", PADDING), ("TILE_STRIDE", STRIDE),
        ("TILES_PER_ROW", COLUMNS), ("FRAME_MS", FRAME_MS),
    ]]
    (output / "frames.rs").write_text(
        "// Generated by tools/prepare-iconly-atlas.py.\n\n"
        + "\n".join(constants)
        + "\n\nimpl Icon {\n"
        + "\n".join(entries)
        + "\n}\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python tools/prepare-iconly-atlas.py <Iconly Local library path>")
    build(Path(sys.argv[1]), Path(__file__).resolve().parents[1] / "assets" / "iconly")
